"""
04_llm_agent.py

A Claude-powered, natural-language "self-serve analytics" agent over the
funnel, experiment, and propensity outputs generated by scripts 01-03 --
the same pattern as a stakeholder self-serve tool: a VP asks a plain-English
question, Claude decides which analytics function(s) to call (tool use),
and returns a grounded answer instead of hallucinating numbers.

Setup:
    export ANTHROPIC_API_KEY=sk-ant-...
    python 01_generate_data.py
    python 02_funnel_and_did_analysis.py
    python 03_upgrade_propensity_model.py

Run (interactive):
    python 04_llm_agent.py

Run (single question):
    python 04_llm_agent.py "Which paid channel converts best for new customers?"
"""

import json
import os
import sys
from pathlib import Path

import pandas as pd
from anthropic import Anthropic

DATA_DIR = Path(__file__).parent / "data"
OUT_DIR = Path(__file__).parent / "output"
MODEL = os.environ.get("CLAUDE_MODEL", "claude-sonnet-5")

# ---------------------------------------------------------------------------
# Tool implementations -- plain Python functions over the CSVs produced by
# scripts 01-03. Claude never sees raw data; it only sees what these
# functions choose to return, which keeps answers grounded and auditable.
# ---------------------------------------------------------------------------

def get_channel_funnel(channel: str = None, segment: str = None) -> dict:
    """Traffic -> signup -> start conversion rates by channel and segment."""
    df = pd.read_csv(OUT_DIR / "channel_funnel_summary.csv")
    if channel:
        df = df[df["channel"] == channel]
    if segment:
        df = df[df["segment"] == segment]
    return df.to_dict(orient="records")


def get_did_result() -> dict:
    """Difference-in-differences result for the upsell flow redesign experiment."""
    exp = pd.read_csv(DATA_DIR / "upsell_experiment.csv")
    means = exp.groupby(["group", "period"])["converted_to_premium"].mean().unstack()
    text_path = OUT_DIR / "did_regression_summary.txt"
    summary_text = text_path.read_text() if text_path.exists() else "Run 02_funnel_and_did_analysis.py first."
    return {
        "raw_group_means": means.to_dict(),
        "regression_summary_excerpt": summary_text[-800:],
    }


def get_top_upgrade_candidates(n: int = 10) -> dict:
    """Top-N customers ranked by predicted upgrade probability."""
    path = OUT_DIR / "top_upgrade_candidates.csv"
    if not path.exists():
        return {"error": "Run 03_upgrade_propensity_model.py first."}
    df = pd.read_csv(path).head(n)
    return df.to_dict(orient="records")


def get_model_metrics() -> dict:
    """Upgrade-propensity model performance (AUC, precision/recall) and top drivers."""
    path = OUT_DIR / "model_metrics.txt"
    if not path.exists():
        return {"error": "Run 03_upgrade_propensity_model.py first."}
    return {"metrics_text": path.read_text()}


TOOLS = [
    {
        "name": "get_channel_funnel",
        "description": "Get traffic->signup->start conversion rates, optionally filtered by channel and/or customer segment (net_new or retained).",
        "input_schema": {
            "type": "object",
            "properties": {
                "channel": {"type": "string", "description": "e.g. paid_search, paid_social, display, video, affiliate, organic"},
                "segment": {"type": "string", "description": "net_new or retained"},
            },
        },
    },
    {
        "name": "get_did_result",
        "description": "Get the difference-in-differences result for the free-to-premium upsell flow redesign experiment (treatment vs control, pre vs post launch).",
        "input_schema": {"type": "object", "properties": {}},
    },
    {
        "name": "get_top_upgrade_candidates",
        "description": "Get the top N customers ranked by predicted upgrade probability, for outreach targeting.",
        "input_schema": {
            "type": "object",
            "properties": {"n": {"type": "integer", "description": "Number of customers to return, default 10"}},
        },
    },
    {
        "name": "get_model_metrics",
        "description": "Get the upgrade-propensity model's accuracy metrics (AUC, precision, recall) and top predictive features.",
        "input_schema": {"type": "object", "properties": {}},
    },
]

TOOL_FUNCS = {
    "get_channel_funnel": lambda **kw: get_channel_funnel(**kw),
    "get_did_result": lambda **kw: get_did_result(),
    "get_top_upgrade_candidates": lambda **kw: get_top_upgrade_candidates(**kw),
    "get_model_metrics": lambda **kw: get_model_metrics(),
}

SYSTEM_PROMPT = (
    "You are a self-serve growth analytics assistant for a freemium SaaS product. "
    "Answer the stakeholder's question using ONLY the analytics tools provided -- "
    "never invent numbers. Cite the specific figures you retrieved. Keep answers "
    "concise and business-facing (a VP audience), and call out statistical "
    "significance or sample-size caveats when relevant."
)


def ask(question: str, client: Anthropic) -> str:
    messages = [{"role": "user", "content": question}]

    while True:
        response = client.messages.create(
            model=MODEL,
            max_tokens=1024,
            system=SYSTEM_PROMPT,
            tools=TOOLS,
            messages=messages,
        )

        if response.stop_reason != "tool_use":
            return "".join(block.text for block in response.content if block.type == "text")

        messages.append({"role": "assistant", "content": response.content})
        tool_results = []
        for block in response.content:
            if block.type == "tool_use":
                func = TOOL_FUNCS[block.name]
                try:
                    result = func(**(block.input or {}))
                except Exception as e:
                    result = {"error": str(e)}
                tool_results.append({
                    "type": "tool_result",
                    "tool_use_id": block.id,
                    "content": json.dumps(result, default=str),
                })
        messages.append({"role": "user", "content": tool_results})


def main():
    if "ANTHROPIC_API_KEY" not in os.environ:
        print("Set ANTHROPIC_API_KEY before running this script.")
        sys.exit(1)

    for required in ["channel_funnel_summary.csv", "did_regression_summary.txt", "top_upgrade_candidates.csv"]:
        if not (OUT_DIR / required).exists():
            print(f"Missing {required} -- run 01_generate_data.py, 02_..., 03_... first.")
            sys.exit(1)

    client = Anthropic()

    if len(sys.argv) > 1:
        question = " ".join(sys.argv[1:])
        print(f"Q: {question}\n")
        print(ask(question, client))
        return

    print("GTM self-serve analytics agent. Ask a question (Ctrl+C to exit).")
    print("Examples:")
    print("  - Which channel has the best signup-to-start rate for new customers?")
    print("  - Did the upsell redesign actually work?")
    print("  - Who are the top 5 customers to target for an upgrade push?\n")
    while True:
        try:
            q = input("> ")
        except (EOFError, KeyboardInterrupt):
            break
        if not q.strip():
            continue
        print(ask(q, client), "\n")


if __name__ == "__main__":
    main()
